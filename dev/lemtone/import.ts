// The Lemtone models (each device's calibration) and the reference solve's
// test vectors, from a checkout of rc-bulb-firmware, as src/shared's
// <device>.model.ts and <device>.vectors.ts. Run it again when the firmware's
// lemtone/ changes:
//
//   node dev/lemtone/import.ts ../rc-bulb-firmware
//
// The models leave out the spectra (vibes works in XYZ). Their numbers keep
// nine significant digits, as the firmware's own generated C does; the
// vectors keep the digits they're printed with.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const DEVICES = [
  { name: "bulb", what: "the color bulbs'", model: "lemtone_model.json", vectors: "lemtone_vectors.h" },
  { name: "panel", what: "the 4×1 panels'", model: "lemtone_model_panel.json", vectors: "lemtone_vectors_panel.h" },
];

const firmware = process.argv[2];
if (!firmware) {
  console.error("usage: node dev/lemtone/import.ts <rc-bulb-firmware checkout>");
  process.exit(1);
}
const out = path.join(import.meta.dirname, "../../src/shared");

interface FirmwareModel {
  id: string;
  knots: number[][];
  xyz: number[][][];
  theta: number[][];
  duty_max: number;
  lm_per_y: number;
  white_sum_max?: number;
  white_grid_log2?: number;
  white_dim_min?: number;
  white_by_dim?: number;
  rated: { lm: number };
}

const num = (v: number) => (Number.isInteger(v) ? String(v) : String(Number(v.toPrecision(9))));
const row = (vs: number[]) => `[${vs.map(num).join(", ")}]`;
const CHANNELS = ["r", "g", "b", "ww", "cw"];

for (const d of DEVICES) {
  const m = JSON.parse(readFileSync(path.join(firmware, "lemtone", d.model), "utf8")) as FirmwareModel;
  const perChannel = (rows: string[]) => rows.map((r, i) => `    ${r}, // ${CHANNELS[i]}`).join("\n");
  writeFileSync(
    path.join(out, `${d.name}.model.ts`),
    `// GENERATED by dev/lemtone/import.ts from rc-bulb-firmware lemtone/${d.model} (${d.what} calibration,
// itself generated by calibration/export_lemtone_model.py); do not edit. Spectra left out.

import type { Model } from "./solver.ts";

export const MODEL: Model = {
  id: ${JSON.stringify(m.id)},
  /** Per channel: r, g, b, ww, cw. */
  knots: [
${perChannel(m.knots.map(row))}
  ],
  xyz: [
${perChannel(m.xyz.map((pts) => `[${pts.map(row).join(", ")}]`))}
  ],
  theta: [
${perChannel(m.theta.map(row))}
  ],
  dutyMax: ${num(m.duty_max)},
  lmPerY: ${num(m.lm_per_y)},
  whiteSumMax: ${num(m.white_sum_max ?? 0)},
  whiteGridLog2: ${m.white_grid_log2 ?? 0},
  whiteDimMin: ${m.white_dim_min ?? 0},
  whiteByDim: ${Boolean(m.white_by_dim)},
  ratedLm: ${num(m.rated.lm)},
};
`,
  );

  // The C initializers, as rows of numbers: { {d…}, {xyz…} } and { a, b, lm, f, mode, desat, lm_out, {duty…}, {period…}, {ticks…} }.
  const header = readFileSync(path.join(firmware, "lemtone/test", d.vectors), "utf8");
  const table = (name: string) => {
    const body = header.slice(header.indexOf(`${name}[] = {`)).split("};")[0]!;
    return body
      .split("\n")
      .filter((l) => l.trim().startsWith("{"))
      .map((l) => (l.match(/-?[\d.]+(?:e[-+]?\d+)?/g) ?? []).map(Number));
  };
  // Forward: the five duties, then XYZ. Solve: a, b, lm, fidelity, mode, desat, lm out, then the five duties (the quantized periods and ticks left out).
  const fwd = table("FWD_VECS").map((v) => v.slice(0, 8));
  const solve = table("SOLVE_VECS").map((v) => v.slice(0, 12));
  const lines = (rows: number[][]) => rows.map((r) => `  ${row(r)},`).join("\n");
  writeFileSync(
    path.join(out, `${d.name}.vectors.ts`),
    `// GENERATED by dev/lemtone/import.ts from rc-bulb-firmware lemtone/test/${d.vectors} (from
// calibration/lemtone_ref.py, the float64 reference solve); do not edit. Model ${m.id}.

/** Each: duties r, g, b, ww, cw, then the XYZ they give. */
export const FORWARD_VECTORS: number[][] = [
${lines(fwd)}
];

/** Each: a, b, lm, fidelity, mode (0 off, 1 exact, 2 desat, 3 clamp), desat, lm out, then duty r, g, b, ww, cw. */
export const SOLVE_VECTORS: number[][] = [
${lines(solve)}
];
`,
  );
  console.log(`${d.name}: ${m.id}, ${fwd.length} forward and ${solve.length} solve vectors`);
}
